import { Router } from "express";
import { authMiddleware, AuthRequest } from "../middleware/auth";
import { loadProfile } from "../middleware/loadProfile";
import { requireModuleAccess } from "../middleware/requireModuleAccess";
import { resolveRequestAccessRoles } from "../auth/accessRoles";
import { DevelopmentPlanStatus, DevelopmentPlanItemStatus } from "@prisma/client";
import prisma from "../prisma";
import { autoGenerateDevelopmentPlans } from "../services/developmentPlan.service";

const router = Router();

const isPrivileged = (roles: string[]) =>
  roles.some((r) => ["super_admin", "hr", "manager"].includes(r));

const parsePlanStatus = (v: unknown): DevelopmentPlanStatus | null => {
  if (v === "draft")     return DevelopmentPlanStatus.draft;
  if (v === "active")    return DevelopmentPlanStatus.active;
  if (v === "completed") return DevelopmentPlanStatus.completed;
  return null;
};

const parseItemStatus = (v: unknown): DevelopmentPlanItemStatus | null => {
  if (v === "pending")     return DevelopmentPlanItemStatus.pending;
  if (v === "in_progress") return DevelopmentPlanItemStatus.in_progress;
  if (v === "completed")   return DevelopmentPlanItemStatus.completed;
  if (v === "deferred")    return DevelopmentPlanItemStatus.deferred;
  return null;
};

// GET /development-plans?profileId=&cycleId=&status=
router.get("/", authMiddleware, loadProfile, async (req: AuthRequest, res) => {
  try {
    const roles = resolveRequestAccessRoles(req).map((r) => r.toLowerCase());
    const myProfileId = req.profile?.id;

    const requestedProfileId = req.query.profileId ? Number(req.query.profileId) : undefined;
    const cycleId = req.query.cycleId ? Number(req.query.cycleId) : undefined;
    const status  = parsePlanStatus(req.query.status) ?? undefined;

    const resolvedProfileId = isPrivileged(roles) && requestedProfileId
      ? requestedProfileId
      : myProfileId;

    if (!resolvedProfileId) return res.status(400).json({ error: "Profile not resolved" });

    const plans = await prisma.developmentPlan.findMany({
      where: {
        profileId: resolvedProfileId,
        ...(cycleId ? { evaluationCycleId: cycleId } : {}),
        ...(status ? { status } : {}),
      },
      include: {
        evaluationCycle: { select: { id: true, cycleName: true } },
        items: {
          include: { competency: { select: { id: true, name: true, category: true } } },
          orderBy: [{ priority: "asc" }, { status: "asc" }],
        },
      },
      orderBy: { createdAt: "desc" },
    });

    return res.json(plans);
  } catch (err: any) {
    return res.status(500).json({ error: "Failed to fetch development plans" });
  }
});

// GET /development-plans/:id
router.get("/:id", authMiddleware, loadProfile, async (req: AuthRequest, res) => {
  try {
    const roles = resolveRequestAccessRoles(req).map((r) => r.toLowerCase());
    const myProfileId = req.profile?.id;
    const plan = await prisma.developmentPlan.findUnique({
      where: { id: Number(req.params.id) },
      include: {
        profile: { select: { id: true, firstName: true, lastName: true } },
        evaluationCycle: { select: { id: true, cycleName: true } },
        items: {
          include: { competency: { select: { id: true, name: true, category: true } } },
          orderBy: [{ priority: "asc" }, { status: "asc" }],
        },
      },
    });
    if (!plan) return res.status(404).json({ error: "Plan not found" });
    if (!isPrivileged(roles) && plan.profileId !== myProfileId) {
      return res.status(403).json({ error: "Access denied" });
    }
    return res.json(plan);
  } catch (err: any) {
    return res.status(500).json({ error: "Failed to fetch plan" });
  }
});

// POST /development-plans
router.post(
  "/",
  authMiddleware,
  loadProfile,
  requireModuleAccess("evaluations", "write"),
  async (req: AuthRequest, res) => {
    try {
      const roles = resolveRequestAccessRoles(req).map((r) => r.toLowerCase());
      const myProfileId = req.profile?.id;
      const { profileId, evaluationCycleId, title, status, notes, items } = req.body;
      if (!title) return res.status(400).json({ error: "title is required" });

      const resolvedProfileId = isPrivileged(roles) && profileId ? Number(profileId) : myProfileId;
      if (!resolvedProfileId) return res.status(400).json({ error: "Profile not resolved" });

      const plan = await prisma.developmentPlan.create({
        data: {
          profileId: resolvedProfileId,
          evaluationCycleId: evaluationCycleId ? Number(evaluationCycleId) : undefined,
          title,
          status: parsePlanStatus(status) ?? DevelopmentPlanStatus.draft,
          notes: notes || undefined,
          items: items?.length
            ? {
                create: (items as any[]).map((item: any, idx: number) => ({
                  competencyId:  item.competencyId ? Number(item.competencyId) : undefined,
                  title:         item.title,
                  description:   item.description || undefined,
                  targetLevel:   item.targetLevel ? Number(item.targetLevel) : undefined,
                  currentLevel:  item.currentLevel ? Number(item.currentLevel) : undefined,
                  priority:      item.priority ?? idx + 1,
                  dueDate:       item.dueDate ? new Date(item.dueDate) : undefined,
                  resources:     item.resources ?? undefined,
                })),
              }
            : undefined,
        },
        include: {
          items: { include: { competency: { select: { id: true, name: true } } } },
        },
      });

      return res.status(201).json(plan);
    } catch (err: any) {
      return res.status(500).json({ error: err?.message || "Failed to create plan" });
    }
  }
);

// PATCH /development-plans/:id
router.patch(
  "/:id",
  authMiddleware,
  loadProfile,
  requireModuleAccess("evaluations", "write"),
  async (req: AuthRequest, res) => {
    try {
      const roles = resolveRequestAccessRoles(req).map((r) => r.toLowerCase());
      const myProfileId = req.profile?.id;
      const id = Number(req.params.id);

      const existing = await prisma.developmentPlan.findUnique({ where: { id } });
      if (!existing) return res.status(404).json({ error: "Plan not found" });
      if (!isPrivileged(roles) && existing.profileId !== myProfileId) {
        return res.status(403).json({ error: "Access denied" });
      }

      const { title, status, notes } = req.body;
      const parsedStatus = parsePlanStatus(status);

      const plan = await prisma.developmentPlan.update({
        where: { id },
        data: {
          ...(title ? { title } : {}),
          ...(parsedStatus ? { status: parsedStatus } : {}),
          ...(notes !== undefined ? { notes } : {}),
        },
        include: {
          items: { include: { competency: { select: { id: true, name: true } } } },
        },
      });

      return res.json(plan);
    } catch (err: any) {
      return res.status(500).json({ error: err?.message || "Failed to update plan" });
    }
  }
);

// PATCH /development-plans/items/:itemId — update a single plan item
router.patch(
  "/items/:itemId",
  authMiddleware,
  loadProfile,
  requireModuleAccess("evaluations", "write"),
  async (req: AuthRequest, res) => {
    try {
      const roles = resolveRequestAccessRoles(req).map((r) => r.toLowerCase());
      const myProfileId = req.profile?.id;
      const itemId = Number(req.params.itemId);

      const item = await prisma.developmentPlanItem.findUnique({
        where: { id: itemId },
        include: { plan: true },
      });
      if (!item) return res.status(404).json({ error: "Item not found" });
      if (!isPrivileged(roles) && item.plan.profileId !== myProfileId) {
        return res.status(403).json({ error: "Access denied" });
      }

      const { title, description, status, priority, dueDate, resources, targetLevel, currentLevel } = req.body;
      const parsedStatus = parseItemStatus(status);
      const completedAt =
        parsedStatus === DevelopmentPlanItemStatus.completed && item.status !== "completed"
          ? new Date()
          : undefined;

      const updated = await prisma.developmentPlanItem.update({
        where: { id: itemId },
        data: {
          ...(title ? { title } : {}),
          ...(description !== undefined ? { description } : {}),
          ...(parsedStatus ? { status: parsedStatus } : {}),
          ...(completedAt ? { completedAt } : {}),
          ...(priority !== undefined ? { priority: Number(priority) } : {}),
          ...(dueDate !== undefined ? { dueDate: dueDate ? new Date(dueDate) : null } : {}),
          ...(resources !== undefined ? { resources } : {}),
          ...(targetLevel !== undefined ? { targetLevel: targetLevel !== null ? Number(targetLevel) : null } : {}),
          ...(currentLevel !== undefined ? { currentLevel: currentLevel !== null ? Number(currentLevel) : null } : {}),
        },
        include: { competency: { select: { id: true, name: true } } },
      });

      return res.json(updated);
    } catch (err: any) {
      return res.status(500).json({ error: err?.message || "Failed to update item" });
    }
  }
);

// DELETE /development-plans/:id
router.delete(
  "/:id",
  authMiddleware,
  loadProfile,
  requireModuleAccess("evaluations", "write"),
  async (req: AuthRequest, res) => {
    try {
      const roles = resolveRequestAccessRoles(req).map((r) => r.toLowerCase());
      const myProfileId = req.profile?.id;
      const id = Number(req.params.id);
      const existing = await prisma.developmentPlan.findUnique({ where: { id } });
      if (!existing) return res.status(404).json({ error: "Plan not found" });
      if (!isPrivileged(roles) && existing.profileId !== myProfileId) {
        return res.status(403).json({ error: "Access denied" });
      }
      await prisma.developmentPlan.delete({ where: { id } });
      return res.status(204).send();
    } catch (err: any) {
      return res.status(500).json({ error: "Failed to delete plan" });
    }
  }
);

// POST /development-plans/generate?cycleId= — manual trigger (HR)
router.post(
  "/generate",
  authMiddleware,
  loadProfile,
  requireModuleAccess("evaluations", "admin"),
  async (req: AuthRequest, res) => {
    try {
      const cycleId = req.query.cycleId ? Number(req.query.cycleId) : Number(req.body.cycleId);
      if (!cycleId) return res.status(400).json({ error: "cycleId is required" });

      autoGenerateDevelopmentPlans(cycleId).catch((err) =>
        console.error("[DevPlan] Auto-generation failed:", err)
      );

      return res.json({ ok: true, message: "Development plan generation started" });
    } catch (err: any) {
      return res.status(500).json({ error: "Failed to trigger generation" });
    }
  }
);

export default router;
