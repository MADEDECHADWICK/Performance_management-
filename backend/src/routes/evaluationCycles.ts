// This file defines the API routes for managing evaluation cycles. It includes endpoints for listing, retrieving, creating, updating, and deleting evaluation cycles. The routes are protected with authentication and role-based access control middleware to ensure that only authorized users can perform certain actions. The implementation also includes utility functions for parsing input values, resolving user roles, and determining access permissions based on those roles. By organizing these routes in a dedicated file, we can maintain a clear structure for our API and facilitate the management of evaluation cycles within the application.

import { Router } from 'express';
import { authMiddleware, AuthRequest } from '../middleware/auth';
import { resolveRequestAccessRoles } from "../auth/accessRoles";
import { loadProfile } from '../middleware/loadProfile';
import { requireModuleAccess } from '../middleware/requireModuleAccess';
import { EvaluationCycleStatus } from '@prisma/client';
import prisma from '../prisma';
import { bridgeAllScoresForCycle } from '../services/evaluationBscBridge.service';
import { autoGenerateDevelopmentPlans } from '../services/developmentPlan.service';
import { resolveEnabledEvaluatorTypes } from '../services/evaluationWorkflow.service';

const router = Router();

const parseCycleStatus = (value: unknown): EvaluationCycleStatus | null => {
  const normalized = String(value || "")
    .trim()
    .toLowerCase();
  if (!normalized) return null;
  if (normalized === "draft") return EvaluationCycleStatus.draft;
  if (normalized === "active") return EvaluationCycleStatus.active;
  if (normalized === "closed") return EvaluationCycleStatus.closed;
  return null;
};

const resolveRoles = (req: AuthRequest) => {
  return resolveRequestAccessRoles(req).map((role) => role.toLowerCase());
};

const isPrivileged = (roles: string[]) =>
  roles.includes('super_admin') ||
  roles.includes('hr');

// GET /evaluation_cycles?status=active
router.get('/', authMiddleware, loadProfile, async (req: AuthRequest, res) => {
  try {
    const { status } = req.query;
    const roles = resolveRoles(req);
    const privileged = isPrivileged(roles);
    const resolvedStatus = privileged
      ? (status as EvaluationCycleStatus | undefined)
      : EvaluationCycleStatus.active;

    const cycles = await prisma.evaluationCycle.findMany({
      where: resolvedStatus ? { status: resolvedStatus } : undefined,
      include: privileged
        ? {
            definitions: true,
            performanceScores: true,
          }
        : {
            definitions: {
              where: { status: 'published', hideFromDashboard: false },
            },
          },
    });
    return res.json(cycles);
  } catch (err: any) {
    console.error('Error fetching evaluation cycles:', err);
    return res.status(500).json({ error: 'Failed to fetch evaluation cycles' });
  }
});

// GET /evaluation_cycles/:id
router.get('/:id', authMiddleware, loadProfile, async (req: AuthRequest, res) => {
  try {
    const { id } = req.params;
    const roles = resolveRoles(req);
    const privileged = isPrivileged(roles);

    const cycle = await prisma.evaluationCycle.findUnique({
      where: { id: parseInt(id) },
      include: privileged
        ? {
            definitions: true,
            performanceScores: true,
          }
        : {
            definitions: {
              where: { status: 'published', hideFromDashboard: false },
            },
          },
    });
    if (!cycle) {
      return res.status(404).json({ error: 'Evaluation cycle not found' });
    }
    if (!privileged && cycle.status !== EvaluationCycleStatus.active) {
      return res.status(403).json({ error: 'Access denied' });
    }
    return res.json(cycle);
  } catch (err: any) {
    console.error('Error fetching evaluation cycle:', err);
    return res.status(500).json({ error: 'Failed to fetch evaluation cycle' });
  }
});

// POST /evaluation_cycles
router.post(
  '/',
  authMiddleware,
  loadProfile,
  requireModuleAccess('evaluations', 'write'),
  async (req: AuthRequest, res) => {
  try {
    const {
      cycle_name,
      cycleName,
      description,
      start_date,
      startDate,
      end_date,
      endDate,
      status
    } = req.body;
    const profileId = req.profile?.id ?? (req.user?.profileId ? Number(req.user.profileId) : undefined);

    const resolvedName = cycleName || cycle_name;
    const resolvedStart = startDate || start_date;
    const resolvedEnd = endDate || end_date;

    if (!resolvedName || !resolvedStart || !resolvedEnd) {
      return res.status(400).json({ error: 'Missing required fields' });
    }

    const startDateObj = new Date(resolvedStart);
    const endDateObj = new Date(resolvedEnd);
    if (Number.isNaN(startDateObj.getTime()) || Number.isNaN(endDateObj.getTime())) {
      return res.status(400).json({ error: 'Invalid start or end date' });
    }
    if (endDateObj <= startDateObj) {
      return res.status(400).json({ error: 'End date must be after start date' });
    }

    const parsedStatus = parseCycleStatus(status);
    if (status !== undefined && status !== null && !parsedStatus) {
      return res.status(400).json({ error: 'Invalid status value' });
    }

    const cycle = await prisma.evaluationCycle.create({
      data: {
        cycleName: resolvedName,
        description,
        startDate: startDateObj,
        endDate: endDateObj,
        status: parsedStatus || EvaluationCycleStatus.draft,
        createdByProfileId: profileId || undefined,
      },
    });
    return res.status(201).json(cycle);
  } catch (err: any) {
    console.error('Error creating evaluation cycle:', err);
    return res.status(500).json({ error: err?.message || 'Failed to create evaluation cycle' });
  }
});

// PATCH /evaluation_cycles/:id
router.patch(
  '/:id',
  authMiddleware,
  loadProfile,
  requireModuleAccess('evaluations', 'write'),
  async (req: AuthRequest, res) => {
  try {
    const { id } = req.params;
    const {
      cycle_name,
      cycleName,
      description,
      start_date,
      startDate,
      end_date,
      endDate,
      status
    } = req.body;

    const parsedStatus = parseCycleStatus(status);
    if (status !== undefined && status !== null && !parsedStatus) {
      return res.status(400).json({ error: 'Invalid status value' });
    }
    const resolvedStart = startDate || start_date;
    const resolvedEnd = endDate || end_date;
    if (resolvedStart && resolvedEnd) {
      const startDateObj = new Date(resolvedStart);
      const endDateObj = new Date(resolvedEnd);
      if (Number.isNaN(startDateObj.getTime()) || Number.isNaN(endDateObj.getTime())) {
        return res.status(400).json({ error: 'Invalid start or end date' });
      }
      if (endDateObj <= startDateObj) {
        return res.status(400).json({ error: 'End date must be after start date' });
      }
    }

    if (parsedStatus === EvaluationCycleStatus.closed) {
      const current = await prisma.evaluationCycle.findUnique({
        where: { id: parseInt(id) },
        select: { status: true },
      });
      if (current?.status !== EvaluationCycleStatus.active) {
        return res.status(409).json({ error: 'Use POST /:id/close to close a cycle, and only active cycles can be closed' });
      }
    }

    const cycle = await prisma.evaluationCycle.update({
      where: { id: parseInt(id) },
      data: {
        ...(cycleName || cycle_name ? { cycleName: cycleName || cycle_name } : {}),
        ...(description && { description }),
        ...(startDate || start_date ? { startDate: new Date(startDate || start_date) } : {}),
        ...(endDate || end_date ? { endDate: new Date(endDate || end_date) } : {}),
        ...(parsedStatus && { status: parsedStatus }),
      },
    });

    if (parsedStatus === EvaluationCycleStatus.closed) {
      bridgeAllScoresForCycle(cycle.id).catch((err) =>
        console.error("[EvalBscBridge] Bulk bridge failed for cycle", cycle.id, err)
      );
      autoGenerateDevelopmentPlans(cycle.id).catch((err) =>
        console.error("[DevPlan] Auto-generation failed for cycle", cycle.id, err)
      );
    }

    return res.json(cycle);
  } catch (err: any) {
    console.error('Error updating evaluation cycle:', err);
    return res.status(500).json({ error: err?.message || 'Failed to update evaluation cycle' });
  }
});

// POST /evaluation_cycles/:id/close
router.post(
  '/:id/close',
  authMiddleware,
  loadProfile,
  requireModuleAccess('evaluations', 'write'),
  async (req: AuthRequest, res) => {
    try {
      const cycleId = parseInt(req.params.id);
      const roles = resolveRoles(req);
      if (!isPrivileged(roles)) {
        return res.status(403).json({ error: 'Only HR or administrators can close evaluation cycles' });
      }

      const cycle = await prisma.evaluationCycle.findUnique({
        where: { id: cycleId },
        include: {
          assignments: { select: { id: true, status: true, evaluatorType: true, relationship: true, evaluationDefinitionId: true } },
          definitions: {
            select: {
              id: true,
              excludeFromScore: true,
              enableSelfEvaluation: true,
              enableDownwardEvaluation: true,
              enablePeerEvaluation: true,
              enableUpwardEvaluation: true,
              enableClientEvaluation: true,
            },
          },
        },
      });

      if (!cycle) return res.status(404).json({ error: 'Evaluation cycle not found' });
      if (cycle.status === EvaluationCycleStatus.closed) {
        return res.status(409).json({ error: 'Cycle is already closed' });
      }
      if (cycle.status === EvaluationCycleStatus.draft) {
        return res.status(409).json({ error: 'Only active cycles can be closed' });
      }

      const incompleteCount = cycle.assignments.filter((a) => a.status !== 'submitted').length;

      // Check that every required evaluator type has at least one submitted assignment per definition
      const coverageWarnings: string[] = [];
      for (const definition of cycle.definitions) {
        if (definition.excludeFromScore) continue;
        const requiredTypes = resolveEnabledEvaluatorTypes(definition as Record<string, any>);
        const submittedForDefinition = cycle.assignments.filter(
          (a) => a.evaluationDefinitionId === definition.id && a.status === 'submitted'
        );
        const coveredTypes = new Set(
          submittedForDefinition.map((a) =>
            String(a.relationship || a.evaluatorType || 'manager').toLowerCase()
          )
        );
        for (const requiredType of requiredTypes) {
          if (!coveredTypes.has(requiredType)) {
            coverageWarnings.push(
              `Definition #${definition.id}: no submitted assignments for required evaluator type '${requiredType}'`
            );
          }
        }
      }

      const closed = await prisma.evaluationCycle.update({
        where: { id: cycleId },
        data: { status: EvaluationCycleStatus.closed },
      });

      bridgeAllScoresForCycle(cycleId).catch((err) =>
        console.error('[EvalBscBridge] Bulk bridge failed for cycle', cycleId, err)
      );
      autoGenerateDevelopmentPlans(cycleId).catch((err) =>
        console.error('[DevPlan] Auto-generation failed for cycle', cycleId, err)
      );

      const warnings: string[] = [];
      if (incompleteCount > 0) {
        warnings.push(`${incompleteCount} assignment(s) were not submitted before cycle was closed`);
      }
      warnings.push(...coverageWarnings);

      return res.json({ ...closed, warnings });
    } catch (err: any) {
      console.error('Error closing evaluation cycle:', err);
      return res.status(500).json({ error: err?.message || 'Failed to close evaluation cycle' });
    }
  }
);

// DELETE /evaluation_cycles/:id
router.delete(
  '/:id',
  authMiddleware,
  loadProfile,
  requireModuleAccess('evaluations', 'write'),
  async (req: AuthRequest, res) => {
  try {
    const { id } = req.params;
    await prisma.evaluationCycle.delete({
      where: { id: parseInt(id) },
    });
    return res.json({ ok: true });
  } catch (err: any) {
    console.error('Error deleting evaluation cycle:', err);
    return res.status(500).json({ error: 'Failed to delete evaluation cycle' });
  }
});

export default router;
