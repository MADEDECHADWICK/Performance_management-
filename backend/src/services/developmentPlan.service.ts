import prisma from "../prisma";

const LOW_SCORE_THRESHOLD = 3; // out of 5 — questions scoring below this trigger a plan item

/**
 * After a cycle closes, auto-generate development plans for every evaluatee
 * whose competency scores fell below the threshold.
 *
 * Logic:
 *  1. Find all submitted, included assignments for the cycle
 *  2. Group EvaluationResponse records by (evaluatee, competency)
 *  3. For each evaluatee, average the scores per competency
 *  4. Any competency average < LOW_SCORE_THRESHOLD → create a DevelopmentPlanItem
 *  5. Upsert one DevelopmentPlan per evaluatee (skip if one already exists for cycle)
 */
export async function autoGenerateDevelopmentPlans(cycleId: number): Promise<void> {
  const cycle = await prisma.evaluationCycle.findUnique({
    where: { id: cycleId },
    select: { id: true, cycleName: true },
  });
  if (!cycle) return;

  const assignments = await prisma.evaluationAssignment.findMany({
    where: {
      cycleId,
      status: "submitted",
      definition: { excludeFromScore: false },
    },
    include: {
      responseRecords: {
        include: {
          question: {
            select: { competencyId: true, category: true },
          },
        },
      },
    },
  });

  // Group: evaluateeProfileId → competencyId → scores[]
  const map = new Map<number, Map<number, { scores: number[]; category: string }>>();

  for (const assignment of assignments) {
    const evaluateeId = assignment.evaluateeProfileId;
    if (!map.has(evaluateeId)) map.set(evaluateeId, new Map());
    const competencyMap = map.get(evaluateeId)!;

    for (const response of assignment.responseRecords) {
      const compId = response.question.competencyId;
      if (!compId || response.score == null) continue;

      if (!competencyMap.has(compId)) {
        competencyMap.set(compId, { scores: [], category: response.question.category });
      }
      competencyMap.get(compId)!.scores.push(response.score);
    }
  }

  if (map.size === 0) return;

  // Load competency names
  const allCompetencyIds = [...new Set(
    [...map.values()].flatMap((cm) => [...cm.keys()])
  )];
  const competencies = await prisma.competency.findMany({
    where: { id: { in: allCompetencyIds } },
    select: { id: true, name: true, levels: true },
  });
  const competencyById = new Map(competencies.map((c) => [c.id, c]));

  await Promise.all(
    [...map.entries()].map(async ([evaluateeId, competencyMap]) => {
      const lowItems: Array<{
        competencyId: number;
        title: string;
        avgScore: number;
        targetLevel: number;
        currentLevel: number;
      }> = [];

      for (const [compId, data] of competencyMap.entries()) {
        const avg = data.scores.reduce((s, v) => s + v, 0) / data.scores.length;
        if (avg < LOW_SCORE_THRESHOLD) {
          const comp = competencyById.get(compId);
          if (!comp) continue;
          lowItems.push({
            competencyId: compId,
            title: `Develop competency: ${comp.name}`,
            avgScore: avg,
            currentLevel: Math.round(avg),
            targetLevel: Math.min(5, Math.round(avg) + 1),
          });
        }
      }

      if (lowItems.length === 0) return;

      // Skip if an auto-generated plan already exists for this evaluatee + cycle
      const existing = await prisma.developmentPlan.findFirst({
        where: { profileId: evaluateeId, evaluationCycleId: cycleId, autoGenerated: true },
      });
      if (existing) return;

      await prisma.developmentPlan.create({
        data: {
          profileId: evaluateeId,
          evaluationCycleId: cycleId,
          title: `Development Plan — ${cycle.cycleName}`,
          status: "draft",
          autoGenerated: true,
          notes: `Auto-generated from ${cycleId} evaluation results. ${lowItems.length} area(s) flagged for development.`,
          items: {
            create: lowItems.map((item, index) => ({
              competencyId: item.competencyId,
              title: item.title,
              description: `Current average score: ${item.avgScore.toFixed(1)} / 5. Target: reach level ${item.targetLevel}.`,
              currentLevel: item.currentLevel,
              targetLevel: item.targetLevel,
              priority: index + 1,
              status: "pending",
            })),
          },
        },
      });
    })
  );
}
